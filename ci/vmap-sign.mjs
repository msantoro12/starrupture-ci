#!/usr/bin/env node
// Signs and verifies the version-map feed.
//
// The feed is what `version-map.mjs export-feed` writes. Signing adds the `seq`
// line after the `format` line and a last line `sig<TAB><keyId><TAB><base64>`:
// an Ed25519 signature (RFC 8032, SHA-512, as Node's crypto signs) over every
// byte before that line. The loader checks it with the public key in its slot
// k1 or k2, before it parses anything.
//
//   node ci/vmap-sign.mjs sign <unsigned-feed> --out <file> --key-id k1|k2
//        [--key-env <NAME> | --key-file <pem>] [--last-seq <n>] [--now <unix seconds>]
//   node ci/vmap-sign.mjs verify <signed-feed> [--last-seq <n>] [--now <unix seconds>]
//        [--pub <keyId>=<64 hex>]... [--allow-test-key]
//
// The private key comes from an environment variable (default VMAP_SIGN_KEY,
// a PEM) or a file, and is never printed. `seq` is the UTC second of signing,
// raised to last + 1 when the clock has not passed the last published `seq`.
// A `seq` more than a day ahead of the clock is refused, at the signer and at
// the verifier: a far-future `seq` would pin every cache. verify refuses a
// feed signed with a key marked TEST unless --allow-test-key is given, so no
// gate passes a test-signed feed by reading past a word in the output.
//
// Exit codes: 0 ok; 3 verify refused the file; 2 usage or input error.

import { createPrivateKey, createPublicKey, sign as edSign, verify as edVerify } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { isMain } from './layout-diff.mjs';
import { FEED_FORMAT, FEED_MAX_BYTES } from './version-map.mjs';

export const EXIT_OK = 0;
export const EXIT_REFUSED = 3;
export const EXIT_ERROR = 2;
export const LOADER_CAP_BYTES = 1024 * 1024;
export const MAX_SEQ_AHEAD = 24 * 60 * 60;

// The public keys the loader trusts, as in its slots k1 and k2.
// TODO(release gate, R10 decision 1 and 2): k1 is the TEST public key that the
// loader's feed reader carries. Its private half is not in any repo. The real
// pair is generated by the owner, the private half goes into the `vmap-sign`
// environment secret of this repo, and the real public half replaces k1 here
// and in the loader. Do not ship a build that trusts the TEST key.
export const PUBLIC_KEYS = {
  k1: { hex: '18eb4c9f4b59b3711317574094f3e6efcf1403a12561a941bb771b2be7e8fd84', test: true },
};

class SignError extends Error {}
const need = (cond, msg) => { if (!cond) throw new SignError(msg); };

const SPKI_PREFIX = Buffer.from('302a300506032b6570032100', 'hex');
function publicKeyFromHex(hex) {
  need(/^[0-9a-f]{64}$/.test(hex), 'a public key is 64 lower-case hex digits');
  return createPublicKey({ key: Buffer.concat([SPKI_PREFIX, Buffer.from(hex, 'hex')]), format: 'der', type: 'spki' });
}

const SEQ_LINE = /^seq\t([1-9][0-9]*)$/;

// unsigned: the export-feed text. Returns the signed text.
export function signFeed(unsigned, privateKeyPem, { keyId, lastSeq = 0, now = Math.floor(Date.now() / 1000) } = {}) {
  need(keyId === 'k1' || keyId === 'k2', "the key ID is 'k1' or 'k2'");
  need(Number.isSafeInteger(lastSeq) && lastSeq >= 0, 'the last seq is a non-negative integer');
  need(Buffer.byteLength(unsigned) <= FEED_MAX_BYTES, `the feed is over ${FEED_MAX_BYTES} bytes`);
  const lines = unsigned.split('\n');
  need(lines[0] === `format\t${FEED_FORMAT}` && lines[lines.length - 1] === '', `expected an unsigned format ${FEED_FORMAT} feed from export-feed`);
  need(!lines.some((l) => l.startsWith('seq\t') || l.startsWith('sig\t') || l.includes('\r')), 'the feed already has a seq or sig line, or a CR');
  const seq = Math.max(now, lastSeq + 1);
  need(seq <= now + MAX_SEQ_AHEAD, `seq ${seq} is more than a day ahead of the clock (${now}); the last published seq looks wrong`);
  const body = [lines[0], `seq\t${seq}`, ...lines.slice(1)].join('\n');
  const signature = edSign(null, Buffer.from(body), createPrivateKey(privateKeyPem));
  return { text: `${body}sig\t${keyId}\t${signature.toString('base64')}\n`, seq };
}

// signed: Buffer or string. keys: { id: { hex, test } }. Returns { keyId, seq, test };
// throws SignError with the reason otherwise.
export function verifyFeed(signed, { keys = PUBLIC_KEYS, lastSeq = null, now = Math.floor(Date.now() / 1000) } = {}) {
  const bytes = Buffer.isBuffer(signed) ? signed : Buffer.from(signed);
  need(bytes.length <= LOADER_CAP_BYTES, `the file is ${bytes.length} bytes, over the loader's ${LOADER_CAP_BYTES}`);
  need(bytes.length > 0 && bytes[bytes.length - 1] === 0x0a, 'the file does not end in LF');
  const sigStart = bytes.lastIndexOf(0x0a, bytes.length - 2) + 1;
  const sigLine = bytes.subarray(sigStart, bytes.length - 1).toString('latin1');
  const m = /^sig\t([a-z0-9]+)\t([A-Za-z0-9+/]{86}==)$/.exec(sigLine);
  need(m, 'the last line is not a sig line');
  const key = Object.hasOwn(keys, m[1]) ? keys[m[1]] : null;
  need(key, `unknown key ID ${m[1]}`);
  const signature = Buffer.from(m[2], 'base64');
  need(signature.length === 64, 'the signature is not 64 bytes');
  const body = bytes.subarray(0, sigStart);
  need(edVerify(null, body, publicKeyFromHex(key.hex), signature), 'the signature does not verify');
  const lines = body.toString('latin1').split('\n');
  need(lines[0] === `format\t${FEED_FORMAT}`, `not a format ${FEED_FORMAT} feed`);
  const sm = SEQ_LINE.exec(lines[1] ?? '');
  need(sm, 'the second line is not a seq line');
  const seq = Number(sm[1]);
  need(Number.isSafeInteger(seq), 'seq is too large');
  need(seq <= now + MAX_SEQ_AHEAD, `seq ${seq} is more than a day ahead of the clock (${now})`);
  if (lastSeq !== null) need(seq > lastSeq, `seq ${seq} does not rise above ${lastSeq}`);
  return { keyId: m[1], seq, test: !!key.test };
}

// switches: options that take no value.
function options(argv, flags, repeated = [], switches = []) {
  const opt = {};
  const rest = [];
  for (let i = 0; i < argv.length; i++) {
    if (!argv[i].startsWith('--')) { rest.push(argv[i]); continue; }
    const name = argv[i].slice(2);
    if (switches.includes(name)) { opt[name] = true; continue; }
    need(flags.includes(name), `unknown option --${name}`);
    need(i + 1 < argv.length, `--${name} needs a value`);
    if (repeated.includes(name)) (opt[name] ??= []).push(argv[++i]);
    else opt[name] = argv[++i];
  }
  return { opt, rest };
}

const int = (s, what) => { need(/^\d+$/.test(s), `${what} is a non-negative integer`); return Number(s); };
const USAGE = 'usage: vmap-sign.mjs sign|verify <feed> [options]; see the comment at the top of ci/vmap-sign.mjs';

export function main(argv) {
  const [cmd, ...args] = argv;
  if (cmd === 'sign') {
    const { opt, rest } = options(args, ['out', 'key-id', 'key-env', 'key-file', 'last-seq', 'now']);
    need(rest.length === 1 && opt.out && opt['key-id'], USAGE);
    need(!(opt['key-env'] && opt['key-file']), 'give --key-env or --key-file, not both');
    const pem = opt['key-file'] ? readFileSync(opt['key-file'], 'utf8') : process.env[opt['key-env'] ?? 'VMAP_SIGN_KEY'];
    need(pem, `no private key: set ${opt['key-env'] ?? 'VMAP_SIGN_KEY'} or pass --key-file`);
    const { text, seq } = signFeed(readFileSync(rest[0], 'utf8'), pem, {
      keyId: opt['key-id'],
      lastSeq: opt['last-seq'] === undefined ? 0 : int(opt['last-seq'], '--last-seq'),
      now: opt.now === undefined ? undefined : int(opt.now, '--now'),
    });
    writeFileSync(opt.out, text);
    process.stdout.write(`signed ${opt.out}: seq ${seq}, key ${opt['key-id']}, ${Buffer.byteLength(text)} bytes\n`);
    return EXIT_OK;
  }
  if (cmd === 'verify') {
    const { opt, rest } = options(args, ['last-seq', 'now', 'pub'], ['pub'], ['allow-test-key']);
    need(rest.length === 1, USAGE);
    let keys = PUBLIC_KEYS;
    if (opt.pub) {
      keys = {};
      for (const p of opt.pub) {
        const m = /^([a-z0-9]+)=([0-9a-f]{64})$/.exec(p);
        need(m, '--pub is <keyId>=<64 lower-case hex digits>');
        keys[m[1]] = { hex: m[2], test: false };
      }
    }
    try {
      const r = verifyFeed(readFileSync(rest[0]), {
        keys,
        lastSeq: opt['last-seq'] === undefined ? null : int(opt['last-seq'], '--last-seq'),
        now: opt.now === undefined ? undefined : int(opt.now, '--now'),
      });
      need(!r.test || opt['allow-test-key'], `the feed is signed with the TEST key ${r.keyId}; pass --allow-test-key to accept it`);
      process.stdout.write(`ok seq=${r.seq} key=${r.keyId}${r.test ? ' TEST-KEY' : ''}\n`);
      return EXIT_OK;
    } catch (e) {
      if (!(e instanceof SignError)) throw e;
      process.stderr.write(`vmap-sign: refused: ${e.message}\n`);
      return EXIT_REFUSED;
    }
  }
  throw new SignError(USAGE);
}

if (isMain(import.meta.url)) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (e) {
    process.stderr.write(`vmap-sign: ${e.message}\n`);
    process.exitCode = EXIT_ERROR;
  }
}
