// Tests for layout-diff.mjs and used-classes.mjs.
//
//   node --test ci/layout-diff.test.mjs
//
// The committed fixtures are trimmed copies of the Game-SDK's Assertions.inl at
// the four builds CL-125368, CL-125897, CL-126119 and CL-127004 (see
// fixtures/layout/README.md). With LAYOUT_FULL_DIR set to the directory that
// `ci/fetch-layout-fixtures.mjs` fills, the full-size suite also runs and
// checks the numbers measured in the v2 design.

