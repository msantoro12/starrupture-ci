const FULL = process.env.LAYOUT_FULL_DIR;
const full = (side, c) => join(FULL, `${side}-${c}.inl`);
const haveFull = FULL && existsSync(full('Client', '659656c'));

test('full data: layout changes per transition (design: 628 / 0 / 300 on the client dumps, 629 / 0 / 300 on the server)', { skip: !haveFull && 'LAYOUT_FULL_DIR not set' }, () => {
  const client = [628, 0, 300];
  const server = [629, 0, 300];
  STEPS.forEach(([a, b], i) => {
    const c = buildReport(loadLayout(full('Client', a)), loadLayout(full('Client', b)), usedQualified);
    const s = buildReport(loadLayout(full('Server', a)), loadLayout(full('Server', b)), usedQualified);
    assert.equal(c.layoutChangedClasses, client[i], `client ${a}->${b}`);
    assert.equal(s.layoutChangedClasses, server[i], `server ${a}->${b}`);
    assert.equal(c.layoutChangedUsedClasses, [6, 0, 2][i]);
    assert.equal(s.layoutChangedUsedClasses, [6, 0, 2][i]);
    const all = buildReport(loadLayout(full('Client', a)), loadLayout(full('Client', b)), usedAll);
    assert.equal(all.changedUsedClasses, [13, 0, 2][i]);
    assert.equal(all.used.unmatchedNames.length, 0);
  });
});

