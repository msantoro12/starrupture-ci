const here = dirname(fileURLToPath(import.meta.url));
const FIX = join(here, 'fixtures', 'layout');
const LAYOUT_DIFF = join(here, 'layout-diff.mjs');
const STEPS = [['abd0ebd', 'f3eb06b'], ['f3eb06b', '0b3c9e6'], ['0b3c9e6', '659656c']];

function run(...args) {
  const r = spawnSync(process.execPath, [LAYOUT_DIFF, ...args], { encoding: 'utf8', windowsHide: true, maxBuffer: 64 * 1024 * 1024 });
  return { code: r.status, out: r.stdout, err: r.stderr };
}

// A tiny Assertions.inl: classes given as { name: { size, align, members: {m: offset} } }.
function inl(classes, { end = true } = {}) {
  const hex = (n) => '0x' + n.toString(16).toUpperCase().padStart(6, '0');
  const lines = ['﻿#pragma once', '', '/*', '* SDK generated by Dumper-7', '*/', '', 'SDK_NAMESPACE_START'];
  for (const [name, c] of Object.entries(classes)) {
    lines.push(`#define DUMPER7_ASSERTS_${name.replace(/::/g, '_')} \\`);
    lines.push(`static_assert(alignof(${name}) == ${hex(c.align ?? 8)}, "Wrong alignment on ${name}"); \\`);
    lines.push(`static_assert(sizeof(${name}) == ${hex(c.size)}, "Wrong size on ${name}"); \\`);
    for (const [m, off] of Object.entries(c.members ?? {})) {
      lines.push(`static_assert(offsetof(${name}, ${m}) == ${hex(off)}, "Member '${name}::${m}' has a wrong offset!"); \\`);
    }
    lines.push('');
  }
  if (end) lines.push('', 'SDK_NAMESPACE_END', '');
  return lines.join('\n');
}

const A = { size: 0x40, members: { X: 0x10, Y: 0x20 } };
const parse = (classes) => parseAssertions(inl(classes), 'test');

// ---- parser ----------------------------------------------------------------

test('parses sizeof, alignof, offsetof, a BOM and namespaced and nested class names', () => {
  const l = parse({ AFoo: A, 'Ns::FBar': { size: 8, align: 4, members: { V: 0 } }, 'ABP_X::FConst': { size: 4, members: {} } });
  assert.deepEqual([...l.keys()], ['AFoo', 'Ns::FBar', 'ABP_X::FConst']);
  assert.equal(l.get('AFoo').get('@size'), 0x40);
  assert.equal(l.get('Ns::FBar').get('@align'), 4);
  assert.equal(l.get('AFoo').get('Y'), 0x20);
});

test('parse errors: unknown assertion, truncated file, empty, conflicting duplicate, class without sizeof', () => {
  assert.throws(() => parseAssertions(inl({ AFoo: A }).replace('SDK_NAMESPACE_END', '') , 't'), ParseError);
  assert.throws(() => parseAssertions(inl({ AFoo: A }) + '\nstatic_assert(sizeof(Z) != 1);\n', 't'), ParseError);
  assert.throws(() => parseAssertions(inl({ AFoo: A }).replace('SDK_NAMESPACE_END', 'int junk;\nSDK_NAMESPACE_END'), 't'), ParseError);
  assert.throws(() => parseAssertions(inl({}), 't'), ParseError);
  const dup = inl({ AFoo: A }).replace('SDK_NAMESPACE_END', `static_assert(sizeof(AFoo) == 0x000050, "Wrong size on AFoo");\nSDK_NAMESPACE_END`);
  assert.throws(() => parseAssertions(dup, 't'), /conflicting duplicate/);
  const nosize = inl({ AFoo: A }).split('\n').filter((x) => !x.includes('sizeof(')).join('\n');
  assert.throws(() => parseAssertions(nosize, 't'), /no sizeof/);
});

test('an identical duplicate assertion is accepted', () => {
  const text = inl({ AFoo: A }).replace('SDK_NAMESPACE_END', `static_assert(sizeof(AFoo) == 0x000040, "Wrong size on AFoo");\nSDK_NAMESPACE_END`);
  assert.equal(parseAssertions(text, 't').get('AFoo').get('@size'), 0x40);
});

test('TSV round trip', () => {
  const l = parse({ AFoo: A, FBar: { size: 8, members: { V: 0 } } });
  const tsv = layoutToTsv(l);
  assert.match(tsv, /^AFoo\t@align\t\t8\nAFoo\t@size\t\t64\nAFoo\tX\t0x000010\t\n/);
  assert.deepEqual(parseTsv(tsv, 't'), l);
  assert.throws(() => parseTsv('AFoo\tX\n', 't'), ParseError);
  assert.throws(() => parseTsv('AFoo\tX\tnope\t\n', 't'), ParseError);
});

// ---- diff ------------------------------------------------------------------

test('diff classifies offset, size, align, added and removed members and whole classes', () => {
  const old = parse({
    AStable: A, AMoved: A, AResized: A, ARealigned: A, AAddedMember: A, ARemovedMember: A, AGone: A,
  });
  const next = parse({
    AStable: A,
    AMoved: { ...A, members: { X: 0x10, Y: 0x28 } },
    AResized: { ...A, size: 0x48 },
    ARealigned: { ...A, align: 4 },
    AAddedMember: { ...A, members: { ...A.members, Z: 0x30 } },
    ARemovedMember: { ...A, members: { X: 0x10 } },
    ANew: A,
  });
  const d = diffLayouts(old, next);
  assert.deepEqual([...d.keys()].sort(), ['AAddedMember', 'AGone', 'AMoved', 'ANew', 'ARealigned', 'ARemovedMember', 'AResized']);
  assert.equal(d.get('AGone').kind, 'removed');
  assert.equal(d.get('ANew').kind, 'added');
  assert.deepEqual(d.get('AMoved').deltas, [{ member: 'Y', type: 'offset', old: 0x20, new: 0x28 }]);
  assert.equal(d.get('AResized').deltas[0].type, 'size');
  assert.equal(d.get('ARealigned').deltas[0].type, 'align');
  assert.equal(d.get('AAddedMember').deltas[0].type, 'added');
  assert.equal(d.get('ARemovedMember').deltas[0].type, 'removed');
  const r = buildReport(old, next, null);
  assert.equal(r.changedClasses, 7);
  assert.equal(r.layoutChangedClasses, 3); // moved, resized, realigned
  assert.deepEqual(r.changedByKind, { changed: 5, added: 1, removed: 1 });
});

test('used filter: unused changes are ignored, used changes are reported with deltas', () => {
  const old = parse({ AUsed: A, AOther: A });
  const next = parse({ AUsed: { ...A, members: { X: 0x18, Y: 0x20 } }, AOther: { ...A, size: 0x50 } });
  const r = buildReport(old, next, new Set(['AUsed']));
  assert.equal(r.changedClasses, 2);
  assert.equal(r.changedUsedClasses, 1);
  assert.equal(r.changedUsed[0].class, 'AUsed');
  assert.deepEqual(r.changedUsed[0].deltas, [{ member: 'X', type: 'offset', old: 0x10, new: 0x18 }]);
  const none = buildReport(old, next, new Set(['AUntouched']));
  assert.equal(none.changedUsedClasses, 0);
  assert.deepEqual(none.used.unmatchedNames, ['AUntouched']);
});

test('no false negative: a used class that disappears or appears counts as changed', () => {
  const withIt = parse({ AUsed: A, AKeep: A });
  const without = parse({ AKeep: A });
  const gone = buildReport(withIt, without, new Set(['AUsed']));
  assert.equal(gone.changedUsedClasses, 1);
  assert.equal(gone.changedUsed[0].kind, 'removed');
  const appeared = buildReport(without, withIt, new Set(['AUsed']));
  assert.equal(appeared.changedUsedClasses, 1);
  assert.equal(appeared.changedUsed[0].kind, 'added');
  // renamed members with unchanged offsets are still a change to a used class
  const renamed = parse({ AUsed: { ...A, members: { X: 0x10, Y2: 0x20 } }, AKeep: A });
  assert.equal(buildReport(withIt, renamed, new Set(['AUsed'])).changedUsedClasses, 1);
});

test('used names match qualified and nested classes', () => {
  const m = matchUsed(new Set(['FBar', 'ABP_X', 'Nope']), ['Ns::FBar', 'ABP_X::FConst', 'ABP_XY', 'FBarBaz']);
  assert.deepEqual([...m.matched.keys()].sort(), ['ABP_X::FConst', 'Ns::FBar']);
  assert.deepEqual(m.unmatched, ['Nope']);
  assert.deepEqual([...parseUsedList('# c\nSDK::UWorld\n::AActor # x\n\nFoo\n')].sort(), ['AActor', 'Foo', 'UWorld']);
});

test('CLI exit codes: 0 unchanged, 3 used class changed, 2 on parse error or bad usage', () => {
  const dir = mkdtempSync(join(tmpdir(), 'layout-diff-'));
  const w = (n, text) => { const p = join(dir, n); writeFileSync(p, text); return p; };
  const old = w('old.inl', inl({ AUsed: A, AOther: A }));
  const same = w('same.inl', inl({ AUsed: A, AOther: A }));
  const otherOnly = w('other.inl', inl({ AUsed: A, AOther: { ...A, size: 0x50 } }));
  const usedMoved = w('used.inl', inl({ AUsed: { ...A, size: 0x50 }, AOther: A }));
  const missing = w('missing.inl', inl({ AOther: A }));
  const trunc = w('trunc.inl', inl({ AUsed: A }, { end: false }));
  const list = w('used.txt', 'AUsed\n');
  assert.equal(run('diff', old, same, '--used', list).code, 0);
  assert.equal(run('diff', old, otherOnly, '--used', list).code, 0);
  assert.equal(run('diff', old, usedMoved, '--used', list).code, 3);
  assert.equal(run('diff', old, missing, '--used', list).code, 3);
  assert.equal(run('diff', old, otherOnly).code, 3); // no filter: everything is used
  assert.equal(run('diff', old, trunc, '--used', list).code, 2);
  assert.equal(run('diff', old, join(dir, 'nope.inl'), '--used', list).code, 2);
  assert.equal(run('diff', old, same, '--used', w('empty.txt', '# nothing\n')).code, 2);
  assert.equal(run('diff', old).code, 2);
  assert.equal(run('bogus').code, 2);
  const out = join(dir, 'r.json');
  assert.equal(run('diff', old, usedMoved, '--used', list, '--out', out).code, 3);
  const report = JSON.parse(readFileSync(out, 'utf8'));
  assert.equal(report.changedUsedClasses, 1);
  assert.equal(report.changedUsed[0].deltas[0].member, '@size');
});

// ---- synthesis -------------------------------------------------------------

test('synthesis: newClient = newServer + (oldClient - oldServer)', () => {
  const oc = parse({ AShared: { size: 0x48, members: { X: 0x18 } }, AClientOnly: A, ACarry: { size: 0x20, members: { Own: 0x10 } } });
  const os = parse({ AShared: { size: 0x40, members: { X: 0x10, SrvOnly: 0x30 } }, AServerOnly: A, ACarry: { size: 0x20, members: {} } });
  const ns = parse({ AShared: { size: 0x50, members: { X: 0x20, SrvOnly: 0x38, Fresh: 0x40 } }, AServerOnly: A, ACarry: { size: 0x20, members: {} } });
  const s = synthesizeClient(oc, os, ns);
  assert.equal(s.get('AShared').get('@size'), 0x58); // 0x50 + 8
  assert.equal(s.get('AShared').get('X'), 0x28); // 0x20 + 8
  assert.equal(s.get('AShared').get('Fresh'), 0x40); // new on the server: no delta known
  assert.equal(s.get('AShared').has('SrvOnly'), false); // server-only member stays out
  assert.equal(s.has('AServerOnly'), false);
  assert.deepEqual([...s.get('AClientOnly')], [...oc.get('AClientOnly')]); // carried unchanged
  assert.equal(s.get('ACarry').get('Own'), 0x10); // client-only member of a shared class
});

// ---- the four historic builds (trimmed fixtures) ----------------------------

const fx = (side, c) => join(FIX, `${side}-${c}.inl`);
const usedAll = parseUsedList(readFileSync(join(FIX, 'used-all.txt'), 'utf8'));
const usedQualified = parseUsedList(readFileSync(join(FIX, 'used-qualified.txt'), 'utf8'));

test('fixtures: used-class counts per transition match the design (6 / 0 / 2) on SDK::-qualified names', () => {
  const expected = [6, 0, 2];
  STEPS.forEach(([a, b], i) => {
    for (const side of ['Client', 'Server']) {
      const r = buildReport(loadLayout(fx(side, a)), loadLayout(fx(side, b)), usedQualified);
      assert.equal(r.layoutChangedUsedClasses, expected[i], `${side} ${a}->${b}`);
      assert.equal(r.changedUsedClasses, expected[i], `${side} ${a}->${b} (any change)`);
    }
  });
});

test('fixtures: the full used list adds the using-namespace classes (13 / 0 / 2)', () => {
  const expected = [13, 0, 2];
  STEPS.forEach(([a, b], i) => {
    const r = buildReport(loadLayout(fx('Client', a)), loadLayout(fx('Client', b)), usedAll);
    assert.equal(r.changedUsedClasses, expected[i]);
    // classes unused by the qualified list but changed are still reported when used
    assert.equal(r.changedClasses, expected[i]);
  });
  const r = run('diff', fx('Client', '0b3c9e6'), fx('Client', '659656c'), '--used', join(FIX, 'used-all.txt'));
  assert.equal(r.code, 3);
  assert.deepEqual(JSON.parse(r.out).changedUsed.map((c) => c.class), ['ACrAPHelper', 'ACrCharacterPlayerBase']);
  assert.equal(run('diff', fx('Client', 'f3eb06b'), fx('Client', '0b3c9e6'), '--used', join(FIX, 'used-all.txt')).code, 0);
});

test('fixtures: synthesis reproduces every row the four dumps share, in both content transitions', () => {
  for (const [a, b] of [STEPS[0], STEPS[2]]) {
    const [oc, os, ns, nc] = [fx('Client', a), fx('Server', a), fx('Server', b), fx('Client', b)].map(loadLayout);
    const r = compareSynthesis(synthesizeClient(oc, os, ns), oc, os, ns, nc);
    assert.ok(r.sharedRows > 500);
    assert.equal(r.sharedRowsExact, r.sharedRows);
    assert.ok(r.movedRows > 0 && r.movedRowsExact === r.movedRows);
    assert.equal(r.wrongRows, 0);
  }
  const cli = run('--synthesize', fx('Client', '0b3c9e6'), fx('Server', '0b3c9e6'), fx('Server', '659656c'), '--check', fx('Client', '659656c'));
  assert.equal(cli.code, 0);
  assert.equal(JSON.parse(cli.out).wrongRows, 0);
});

// ---- used-classes ----------------------------------------------------------

const names = (src, known = null) => {
  const out = new Set();
  for (const { name, unqualified, derived } of extractFromSource(src)) {
    if (known ? !known(name) : derived || (unqualified && !/^[UAFETIS][A-Z]\w*$/.test(name))) continue;
    out.add(name);
  }
  return out;
};

test('used-classes: SDK:: qualified, templates, pointers, casts, aliases, using-declarations', () => {
  const src = `
    // SDK::UCommented is not a use
    const char* s = "SDK::UString";
    void f(SDK::AActor* a, const SDK::TArray<SDK::UObject*>& v, SDK::TSubclassOf<SDK::UClass> c) {
      auto p = static_cast<SDK::ACrCharacterPlayerBase*>(a);
      SDK::Ns::FThing t; auto g = SDK::UObject::GObjects;
    }
    using Alias = SDK::UWorld;
    using SDK::UEngine;`;
  const n = names(src);
  for (const x of ['AActor', 'TArray', 'UObject', 'TSubclassOf', 'UClass', 'ACrCharacterPlayerBase', 'Ns::FThing', 'UWorld', 'UEngine']) assert.ok(n.has(x), x);
  assert.ok(!n.has('UCommented') && !n.has('UString'));
});

test('used-classes: using namespace SDK and namespace SDK blocks give unqualified names', () => {
  const withUsing = names('using namespace SDK;\nvoid f(AActor* a, UCrBuildingData* b, int count, TArray<FVector> v) {}\n');
  for (const x of ['AActor', 'UCrBuildingData', 'TArray', 'FVector']) assert.ok(withUsing.has(x), x);
  assert.ok(!withUsing.has('count'));
  const block = names('namespace SDK { class AActor; struct FRotator; }\nclass Mine {};\n');
  assert.ok(block.has('AActor') && block.has('FRotator') && !block.has('Mine'));
  const neither = names('class AActor; void f(AActor*);\n');
  assert.equal(neither.size, 0);
});

test('used-classes: --known keeps only real classes and resolves function parameter structs', () => {
  const known = knownFilter([parse({ AActor: A, UGameplayStatics: A, GameplayStatics_GetPlayerPawn: A, KismetSystemLibrary_IsServer: A })]);
  const n = names('auto p = SDK::UGameplayStatics::GetPlayerPawn(w, 0); SDK::Params::KismetSystemLibrary_IsServer q; SDK::AActor* a; SDK::EnumThing e;', known);
  assert.deepEqual([...n].sort(), ['AActor', 'GameplayStatics_GetPlayerPawn', 'KismetSystemLibrary_IsServer', 'UGameplayStatics']);
});

test('used-classes: comments and string literals are blanked, lengths preserved', () => {
  const src = 'a // x "y"\n/* SDK::A\n */ "q\\"SDK::B" R"x(SDK::C)x" \'"\' SDK::D';
  const out = stripNonCode(src);
  assert.equal(out.length, src.length);
  assert.ok(!/SDK::[ABC]/.test(out));
  assert.match(out, /SDK::D/);
});

